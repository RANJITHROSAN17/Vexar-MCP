"""Scaffolding for ``vexar-mcp init``.

The command exists for one reason: adoption is a three-file chore (config, workflow,
first scan) and most projects never get past the first one. What it must *not* do is
generate a plausible-looking file that the tool then rejects — so every generated
configuration is parsed back through the real loader before it is written.

Two design rules follow from that:

1. **Never write a config the tool would refuse.** :func:`render_config_text` validates
   its own output, so a bug in the template fails the command instead of handing a user
   a broken file they have to debug.
2. **Never write a partial scaffold.** All targets are checked before anything is
   written, so a refusal leaves the directory exactly as it was.
"""

from __future__ import annotations

import tempfile
from dataclasses import dataclass
from pathlib import Path

from mcp_doctor import __version__
from mcp_doctor.config import CONFIG_FILENAMES, discover_config, load_config
from mcp_doctor.models import ScanConfig, Severity
from mcp_doctor.policies import list_policies, resolve_policy

CONFIG_FILENAME = CONFIG_FILENAMES[0]
WORKFLOW_PATH = Path(".github") / "workflows" / "vexar-mcp.yml"
ACTION_REPOSITORY = "RANJITHROSAN17/Vexar-MCP"
MOVING_REFS = frozenset({"main", "master"})

_SEVERITY_BY_VALUE = {severity.value: severity for severity in Severity}


@dataclass(frozen=True)
class ScaffoldFile:
    """One file to write, with the exact text that will land on disk."""

    path: Path
    content: str


@dataclass(frozen=True)
class ScaffoldPlan:
    """The files to write, plus any reason to refuse the whole operation."""

    files: tuple[ScaffoldFile, ...]
    problems: tuple[str, ...]

    @property
    def is_blocked(self) -> bool:
        return bool(self.problems)


def _quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_config_text(preset: str | None = None) -> str:
    """Return a commented ``vexar-mcp.toml`` with the effective defaults for a preset.

    Values are read from the live policy preset and ``ScanConfig`` defaults rather than
    copied into the template, so regenerating the scaffold after a policy change cannot
    produce documentation that disagrees with the tool.

    Args:
        preset: Preset name whose gate values are written as explicit defaults.

    Returns:
        The file text, guaranteed to load through :func:`mcp_doctor.config.load_config`.

    Raises:
        PolicyViolation: If ``preset`` is not a known preset name.
    """
    policy = resolve_policy(preset)
    defaults = ScanConfig()
    default_excludes = ", ".join(_quote(name) for name in defaults.exclude_globs)
    available = ", ".join(item.name for item in list_policies())
    # A policy the tool does not know about would make the generated file fail on the very
    # first scan, so say so rather than falling back to the default preset.
    runnable = {item.name for item in list_policies()}
    if policy.name not in runnable:  # pragma: no cover - resolve_policy already guarantees this
        raise ValueError(f"unknown policy preset '{policy.name}'")

    text = f"""\
# Vexar-MCP configuration -- generated by `vexar-mcp init` (vexar-mcp {__version__}).
#
# Every key below is optional. The values are the ones the '{policy.name}' policy would
# apply anyway, so deleting a line you do not care about changes nothing.
#
# Check what a scan actually uses -- file, preset and flags combined -- with:
#     vexar-mcp scan --print-config
#
# Enforcement preset: {available}.
# `default` fails on errors only; `ci` fails on warnings with a B (80) score floor;
# `strict-prod` and `enterprise-governance` fail on more and forbid ignoring security rules.
policy = {_quote(policy.name)}

# Lowest severity that fails the run: error, warning, info, never.
fail-on = {_quote(policy.fail_on.value)}

# Fail when the health score is below this (0-100). 0 disables the floor.
min-score = {policy.min_score}

# Per-tool context budget in tokens (rule MCP002). A tool definition is re-sent to the
# model on every turn, so this is a recurring cost, not a one-off file size.
max-tool-tokens = {policy.max_tool_tokens}

# Whole-catalog context budget in tokens (rule MCP014).
max-server-tokens = {policy.max_server_tokens}

# Rules to silence, e.g. ignore = ["MCP004", "MCP008"].
# Prefer a baseline over ignoring: `vexar-mcp baseline write` records today's findings and
# fails only on new ones, so existing debt stays visible instead of disappearing.
ignore = []

# Paths to skip, matched against directory names and path suffixes.
#
# CAUTION: setting this REPLACES the built-in skip list, which is currently:
#     {default_excludes}
# Leaving it empty -- as generated here -- keeps that list. To add one directory without
# dropping the rest, copy the built-in names into your list first.
exclude = []

# Optional: extra rule packs (TOML/JSON paths, or trusted module names).
# rule-packs = ["./policies/acme-rules.toml"]

# Optional: committed baseline so only newly introduced findings fail CI.
# baseline = ".vexar-baseline.json"
"""
    _validate_config_text(text)
    return text


def _validate_config_text(text: str) -> None:
    """Raise ``ValueError`` unless the generated text loads as a real configuration.

    Written to a temporary directory and fed through the production loader, because the
    only check that matters is the one the user's first scan will perform.
    """
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / CONFIG_FILENAME
        path.write_text(text, encoding="utf-8")
        load_config(config_path=path, start_dir=Path(tmp))


def render_workflow_text(action_ref: str = "main") -> str:
    """Return a GitHub Actions workflow that gates the repository with Vexar-MCP.

    Args:
        action_ref: Ref of :data:`ACTION_REPOSITORY` to use. ``main`` is the documented
            default; any other value (a tag or commit SHA) pins the tool.

    Returns:
        The workflow file text.
    """
    ref = action_ref.strip() or "main"
    moving = ref in MOVING_REFS
    pin_note = (
        "# Tracks the development branch: your CI changes whenever upstream does.\n"
        "# Pin a released tag or commit SHA (see --action-ref) to make upgrades deliberate."
        if moving
        else "# Pinned: tool upgrades are a deliberate change."
    )
    return f"""\
# Vexar-MCP -- security, schema and token-cost gate for MCP tool definitions.
# Generated by `vexar-mcp init --github-action` (vexar-mcp {__version__}).
{pin_note}
name: Vexar-MCP

on:
  push:
    branches: [main]
  pull_request:

permissions:
  contents: read
  security-events: write  # required by the SARIF upload step below

jobs:
  vexar-mcp:
    name: Scan MCP tool definitions
    runs-on: ubuntu-latest
    steps:
      - name: Check out repository
        uses: actions/checkout@v7

      - name: Scan for security, schema and token issues
        id: vexar
        uses: {ACTION_REPOSITORY}@{ref}
        with:
          path: .
          # `ci` fails on warnings with a B (80) score floor. Gate only on new findings by
          # generating a baseline first: `vexar-mcp baseline write` and commit the result.
          policy: ci
          sarif-output: vexar-mcp.sarif

      - name: Upload findings to code scanning
        if: always()  # upload even when the gate fails -- those are the findings that matter
        uses: github/codeql-action/upload-sarif@v4
        with:
          sarif_file: vexar-mcp.sarif
          category: vexar-mcp
"""


def plan_scaffold(
    target: Path,
    *,
    github_action: bool = False,
    force: bool = False,
    policy: str | None = None,
    action_ref: str = "main",
) -> ScaffoldPlan:
    """Decide what ``init`` would write, without writing it.

    Args:
        target: Project directory to scaffold.
        github_action: Also write :data:`WORKFLOW_PATH`.
        force: Overwrite existing files instead of refusing.
        policy: Preset name used for the generated config's gate values.
        action_ref: Ref used in the generated workflow.

    Returns:
        A plan whose ``problems`` explain every reason to refuse. Empty when writable.
    """
    problems: list[str] = []
    if not target.exists():
        problems.append(f"{target} does not exist; create the project directory first")
        return ScaffoldPlan(files=(), problems=tuple(problems))
    if not target.is_dir():
        problems.append(f"{target} is not a directory")
        return ScaffoldPlan(files=(), problems=tuple(problems))

    config_path = target / CONFIG_FILENAME
    files = [ScaffoldFile(path=config_path, content=render_config_text(policy))]
    if github_action:
        files.append(
            ScaffoldFile(path=target / WORKFLOW_PATH, content=render_workflow_text(action_ref))
        )

    if not force:
        existing = [file.path for file in files if file.path.exists()]
        if existing:
            problems.append(
                "refusing to overwrite existing file(s): "
                + ", ".join(str(path) for path in existing)
                + ". Pass --force to replace them."
            )
        # A second config file does not merely duplicate the first: the loader prefers
        # `vexar-mcp.toml`, so writing one silently changes how an existing project is
        # scanned. Refuse and name the file instead.
        discovered = discover_config(target)
        if discovered is not None and discovered != config_path:
            problems.append(
                f"this project is already configured by {discovered}. "
                f"Writing {CONFIG_FILENAME} would take precedence over it. "
                "Edit the existing file, or pass --force to add a second one."
            )
    return ScaffoldPlan(files=tuple(files), problems=tuple(problems))


def write_scaffold(plan: ScaffoldPlan) -> tuple[Path, ...]:
    """Write every file in ``plan`` and return the paths created."""
    written: list[Path] = []
    for file in plan.files:
        file.path.parent.mkdir(parents=True, exist_ok=True)
        file.path.write_text(file.content, encoding="utf-8")
        written.append(file.path)
    return tuple(written)


def describe_next_steps(target: Path, *, github_action: bool) -> str:
    """Return the short "what now" block printed after a successful scaffold."""
    lines = [
        "Next:",
        f"  1. vexar-mcp scan {target} --print-config   # confirm the effective settings",
        f"  2. vexar-mcp scan {target}                   # see what it finds today",
        "  3. vexar-mcp baseline write                # optional: gate only on new findings",
    ]
    if github_action:
        lines.append(f"  4. git add {CONFIG_FILENAME} {WORKFLOW_PATH} && git commit")
    else:
        lines.append("  4. re-run with --github-action to add a CI workflow")
    return "\n".join(lines)


